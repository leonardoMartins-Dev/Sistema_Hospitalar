-- =========================================================
-- PACIENTES (models/Paciente.java)
-- Cadastrados pela página /register. É também o login do paciente.
-- =========================================================

create table public.pacientes (
    id               bigint      generated by default as identity primary key,
    email            text        not null unique,
    password_hash    text        not null,
    nome             text        not null,
    cpf              text        not null unique,   -- só números
    telefone         text        not null,
    endereco         text        not null,
    data_nascimento  date        not null,
    created_at       timestamptz not null default now()
);


-- =========================================================
-- PROFISSIONAIS DA SAÚDE (models/ProfissionalSaude.java)
-- Cadastrados pelo admin na página /admin/medicos. É também o login do médico.
-- Uma tabela para as 3 subclasses (SINGLE_TABLE); a coluna "tipo" diz qual é.
-- =========================================================

create table public.profissionais_saude (
    id                     bigint      generated by default as identity primary key,
    tipo                   text        not null
                           check (tipo in ('CLINICO_GERAL', 'ESPECIALISTA', 'CIRURGIAO')),
    nome                   text        not null,
    registro_profissional  text        not null unique,   -- ex.: CRM 123456-MG
    telefone               text        not null,
    email                  text        not null unique,
    password_hash          text        not null,

    -- só ESPECIALISTA (MedicoEspecialista)
    especialidade          text
                           check (especialidade in ('CARDIOLOGIA', 'DERMATOLOGIA', 'GINECOLOGIA',
                                                    'NEUROLOGIA', 'ORTOPEDIA', 'PEDIATRIA')),
    -- só CIRURGIAO (Cirurgiao)
    area_cirurgica         text,

    created_at             timestamptz not null default now(),

    check (tipo <> 'ESPECIALISTA' or especialidade is not null),
    check (tipo <> 'CIRURGIAO' or area_cirurgica is not null)
);


-- =========================================================
-- QUARTOS (models/Quarto.java)
-- O limite de leitos de cada tipo fica no enum TipoQuarto (Java).
-- =========================================================

create table public.quartos (
    id                 bigint      generated by default as identity primary key,
    numero             text        not null unique,
    andar              integer     not null,
    tipo               text        not null
                       check (tipo in ('ENFERMARIA', 'APARTAMENTO', 'UTI')),
    capacidade_maxima  integer     not null check (capacidade_maxima > 0),
    ocupacao_atual     integer     not null default 0,
    created_at         timestamptz not null default now(),

    -- Regra de Negócio 5: a ocupação nunca passa da capacidade
    check (ocupacao_atual between 0 and capacidade_maxima)
);


-- =========================================================
-- ATENDIMENTOS (models/Atendimento.java e subclasses)
-- As 4 modalidades numa tabela só (SINGLE_TABLE); a coluna "tipo" diz qual é.
-- As colunas de uma modalidade ficam null nas linhas das outras.
-- =========================================================

create table public.atendimentos (
    id                      bigint      generated by default as identity primary key,
    tipo                    text        not null
                            check (tipo in ('ROTINA', 'ESPECIALIZADA', 'EMERGENCIA', 'CIRURGIA')),
    paciente_id             bigint      not null references public.pacientes(id),
    -- null só na emergência que ainda aguarda avaliação (o médico entra ao assumir)
    profissional_id         bigint      references public.profissionais_saude(id),
    data                    date        not null,
    horario                 time        not null,
    motivo                  text,
    observacoes             text,

    -- cada modalidade grava aqui o próprio enum de situação
    -- (StatusConsulta, StatusEmergencia ou StatusProcedimento)
    status                  text        not null
                            check (status in ('AGENDADA', 'CONFIRMADA', 'EM_ATENDIMENTO', 'CONCLUIDA',
                                              'CANCELADA', 'NAO_COMPARECEU',
                                              'AGUARDANDO_AVALIACAO', 'CONCLUIDO',
                                              'AGENDADO', 'EM_ANDAMENTO', 'CANCELADO')),

    -- ROTINA (ConsultaRotina): especialidade para a qual o clínico encaminhou
    encaminhamento          text
                            check (encaminhamento in ('CARDIOLOGIA', 'DERMATOLOGIA', 'GINECOLOGIA',
                                                      'NEUROLOGIA', 'ORTOPEDIA', 'PEDIATRIA')),
    -- ESPECIALIZADA (ConsultaEspecializada)
    especialidade           text
                            check (especialidade in ('CARDIOLOGIA', 'DERMATOLOGIA', 'GINECOLOGIA',
                                                     'NEUROLOGIA', 'ORTOPEDIA', 'PEDIATRIA')),
    -- EMERGENCIA (AtendimentoEmergencia)
    prioridade              text
                            check (prioridade in ('BAIXA', 'MODERADA', 'ALTA', 'CRITICA')),
    -- CIRURGIA (ProcedimentoCirurgico)
    descricao_procedimento  text,
    tipo_cirurgia           text
                            check (tipo_cirurgia in ('ELETIVA', 'URGENCIA', 'EMERGENCIA')),
    obs_pre_operatorias     text,
    obs_pos_operatorias     text,
    inicio_efetivo          timestamp,                          -- LocalDateTime no Java
    fim_efetivo             timestamp,

    created_at              timestamptz not null default now(),

    check (tipo = 'EMERGENCIA' or profissional_id is not null),
    check (tipo <> 'ESPECIALIZADA' or especialidade is not null),
    check (tipo <> 'EMERGENCIA' or prioridade is not null),
    check (tipo <> 'CIRURGIA' or (descricao_procedimento is not null and tipo_cirurgia is not null))
);

-- Regra de Negócio 3: um profissional não pode ter dois atendimentos no mesmo
-- dia e horário. Emergência não marca horário, e o que foi cancelado libera o
-- horário (CANCELADA na consulta, CANCELADO na cirurgia).
create unique index atendimentos_profissional_horario_uk
    on public.atendimentos (profissional_id, data, horario)
    where tipo <> 'EMERGENCIA' and status not in ('CANCELADA', 'CANCELADO');


-- =========================================================
-- INTERNAÇÕES (models/Internacao.java)
-- =========================================================

create table public.internacoes (
    id                  bigint      generated by default as identity primary key,
    paciente_id         bigint      not null references public.pacientes(id),
    profissional_id     bigint      not null references public.profissionais_saude(id),
    quarto_id           bigint      not null references public.quartos(id),
    data_entrada        date        not null,
    data_prevista_alta  date        check (data_prevista_alta >= data_entrada),
    data_efetiva_alta   date        check (data_efetiva_alta >= data_entrada),  -- preenchida na alta
    observacoes         text,
    status              text        not null default 'ATIVA'
                        check (status in ('ATIVA', 'ALTA')),
    created_at          timestamptz not null default now()
);

-- Um paciente não pode estar internado duas vezes ao mesmo tempo.
create unique index internacoes_paciente_ativa_uk
    on public.internacoes (paciente_id)
    where status = 'ATIVA';


