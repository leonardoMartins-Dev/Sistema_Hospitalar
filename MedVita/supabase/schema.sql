-- =========================================================
-- SEGURANÇA (RLS)
-- =========================================================

-- O Supabase expõe o schema "public" numa API REST pública (usa a "anon key",
-- que fica visível em qualquer front-end). Sem RLS, qualquer pessoa com essa
-- chave conseguiria ler as tabelas, inclusive os hashes de senha.
-- Ligando o RLS SEM criar nenhuma policy, a API REST fica bloqueada.
-- O Spring Boot continua funcionando porque conecta como "postgres", o dono
-- das tabelas, que não é afetado pelo RLS.
alter table public.pacientes           enable row level security;
alter table public.profissionais_saude enable row level security;
alter table public.quartos             enable row level security;
alter table public.consultas           enable row level security;
alter table public.internacoes         enable row level security;
